#include "hw_sce_rx_private.h"

fsp_err_t HW_SCE_GenerateRandomNumberSub (uint32_t OutData_Text[])
{
    if (RD1_MASK(REG_14BCH, 0x0000001fU) != 0)
    {
        return FSP_ERR_CRYPTO_SCE_RESOURCE_CONFLICT;
    }

    WR1_PROG(REG_1B00H, 0x00200002U);
    WR1_PROG(REG_144CH, 0x00000000U);

    HW_SCE_p_func100(0xe413ea77U, 0xfc21a94fU, 0x6053391aU, 0x1916c4baU);
    HW_SCE_p_func103();
    HW_SCE_p_func100(0xda3d5a86U, 0xaabf0908U, 0xc609a7a2U, 0x8dd6bd1cU);
    WR1_PROG(REG_1444H, 0x000000a2U);
    WR1_PROG(REG_1A24H, 0x0c200104U);
    WAIT_STS(REG_1444H, 31, 1);
    WR1_PROG(REG_1420H, change_endian_long(0x00000000U));

    WR1_PROG(REG_1408H, 0x00002012U);
    WAIT_STS(REG_1408H, 30, 1);
    RD4_ADDR(REG_1420H, &OutData_Text[0]);

    HW_SCE_p_func102(0x9bc04526U, 0xa3f9eef2U, 0x6ff35143U, 0x8557f3bcU);

    WR1_PROG(REG_14BCH, 0x00000040U);
    WAIT_STS(REG_142CH, 12, 0);

    return FSP_SUCCESS;
}
