    {
        return FSP_ERR_CRYPTO_SCE_RESOURCE_CONFLICT;
    }

    WR1_PROG(REG_1B00H, 0x000a0001U);
    WR1_PROG(REG_144CH, 0x00000000U);

    HW_SCE_p_func100(0x04cd7004U, 0x2515c081U, 0x0d04ae60U, 0x6769890aU);
    HW_SCE_p_func103();
