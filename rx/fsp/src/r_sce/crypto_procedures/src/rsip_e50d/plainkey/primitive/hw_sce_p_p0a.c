    WR1_PROG(REG_1420H, change_endian_long(0x00000000U));

    WR1_PROG(REG_1608H, 0x80010000U);
    WR1_PROG(REG_1400H, 0x03420005U);
    WAIT_STS(REG_1404H, 30, 0);
    WR1_PROG(REG_143CH, 0x00001800U);
    WR1_PROG(REG_1400H, 0x0002000dU);
    WAIT_STS(REG_1404H, 30, 0);
    WR1_PROG(REG_143CH, 0x00001800U);

    WR1_PROG(REG_1600H, 0x000034e0U);

    WR1_PROG(REG_1444H, 0x000000a7U);
    WR1_PROG(REG_1608H, 0x800103a0U);
    WAIT_STS(REG_1444H, 31, 1);
    WR1_PROG(REG_1420H, change_endian_long(0x0000000aU));
    WR1_PROG(REG_1458H, 0x00000000U);

    HW_SCE_p_func101(0x0dc7da62U, 0xe697cac8U, 0x3bfeaa4cU, 0xda06568fU);
    HW_SCE_p_func043();

    WR1_PROG(REG_1600H, 0x0000b4e0U);
    WR1_PROG(REG_1600H, 0x0000001aU);

    WR1_PROG(REG_1444H, 0x000000a7U);
    WR1_PROG(REG_1608H, 0x800103a0U);
    WAIT_STS(REG_1444H, 31, 1);
    WR1_PROG(REG_1420H, change_endian_long(0x0000000aU));
    WR1_PROG(REG_1458H, 0x00000000U);

    HW_SCE_p_func101(0x8b4de426U, 0x68d4ce46U, 0x2d34b216U, 0xae458995U);
    HW_SCE_p_func044();

    HW_SCE_p_func100(0x7a1bdb19U, 0x09fbdb48U, 0xdd77ce24U, 0x1a67b59dU);
    WR1_PROG(REG_1608H, 0x81010000U);
    WR1_PROG(REG_1408H, 0x00005006U);
    WAIT_STS(REG_1408H, 30, 1);
    RD1_ADDR(REG_1420H, &OutData_KeyIndex[0]);

    HW_SCE_p_func100(0xbba5e5d7U, 0x6f740c24U, 0x1fe80fb2U, 0xa3dd7e0bU);
