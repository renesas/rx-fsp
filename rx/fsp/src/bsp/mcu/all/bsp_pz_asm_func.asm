_bsp_set_trctb:
    trmvtc r1, trctb
    rts

;/***********************************************************************************************************************
; * Assembler functions for __SET_WINTB functions in bsp_pz_hypervisor.c.
; **********************************************************************************************************************/
_bsp_set_wintb:
    trmvtc r1, wintb
    rts

;/***********************************************************************************************************************
; * Assembler functions for R_BSP_SecureEnter functions in bsp_pz_hypervisor.c.
; **********************************************************************************************************************/
_R_BSP_SecureEnter_ASM:
    push.l r3
    mov.l  #00000100h, r5              ; Set WID.BWID = 1(Secure)
    mvtc   r5, wid
    push.l r1                          ; Push PSW to ISP_TR
    push.l r2                          ; Push Secure Entry to ISP_TR
    trrte                              ; Call *pc_adrs
 _R_BSP_SecureEnter_ASM_end:
    bra.b  _R_BSP_SecureEnter_ASM_end  ; Never reach here
    rts

;/***********************************************************************************************************************
; * Assembler functions for R_BSP_NonSecureEnter functions in bsp_security.c.
; **********************************************************************************************************************/
_R_BSP_NonSecureEnter_ASM:
    trcall #0             ; BSP_PZ_TRCALL_VECTOR_ENTER_NS defined 0.
 _SpinProtectZone_end:
    bra.b _SpinProtectZone_end

    .endif ; _RX_PZ_SECURE

