    .glb _bsp_prv_software_delay_loop
    .glb _NMI_Handler
    .glb _bsp_nmi_handler
    .glb _brk_isr
    .glb _break_event_hook
    .glb _bsp_set_ivc

;/***********************************************************************************************************************
; * Section definitions
; **********************************************************************************************************************/

    .section .text,CODE

;/***********************************************************************************************************************
; * This assembly language routine takes roughly 4 cycles per loop. 2 additional cycles occur when the loop exits.
; **********************************************************************************************************************/
_bsp_prv_software_delay_loop:
    bra.b loop
    nop
    loop:
    nop
    sub #01H, r1
    bne.b loop
    rts

;/***********************************************************************************************************************
; * Non-maskable interrupt handler.
; **********************************************************************************************************************/
_NMI_Handler:
    pushm  r1-r15
    bsr.a _bsp_nmi_handler
    popm   r1-r15
    loop2:
    bra.b loop2

;/***********************************************************************************************************************
; * Brk-instruction interrupt handler.
; **********************************************************************************************************************/
_brk_isr:
    pushm  r1-r15
    bsr.a _break_event_hook
    popm   r1-r15
    rte

;/***********************************************************************************************************************
; * IVC Register setting
; **********************************************************************************************************************/
_bsp_set_ivc:
    mvtc r1, ivc
    rts

